import { spawnSync } from "node:child_process"
import { createHash } from "node:crypto"
import fs from "node:fs/promises"
import path from "node:path"
import { pipeline } from "node:stream/promises"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import zlib from "node:zlib"

const require = createRequire(import.meta.url)
const tar = require("tar-stream")

const here = path.dirname(fileURLToPath(import.meta.url))
const pluginRoot = path.resolve(here, "..")
const buildRoot = path.join(here, ".build")
const stageRoot = path.join(buildRoot, "payload")
const distRoot = path.join(here, "dist")

const PAYLOAD_FILES = [
  "index.ts",
  "rpc.ts",
  "settings.ts",
  "package.json",
  "README.md",
  "src/gui.tsx",
  "src/gui/definition.ts",
  "src/gui/page.tsx",
  "dist/gui-experimental.cjs",
]

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex")
}

function humanSize(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`
}

async function stagePayload() {
  await fs.rm(stageRoot, { recursive: true, force: true })
  await fs.mkdir(stageRoot, { recursive: true })
  for (const file of PAYLOAD_FILES) {
    const source = path.join(pluginRoot, file)
    const destination = path.join(stageRoot, file)
    await fs.mkdir(path.dirname(destination), { recursive: true })
    await fs.copyFile(source, destination)
  }

  const pkg = JSON.parse(await fs.readFile(path.join(stageRoot, "package.json"), "utf8"))
  const manifest = {
    name: pkg.name,
    version: pkg.version,
    files: PAYLOAD_FILES,
  }
  await fs.writeFile(path.join(stageRoot, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`)
  return manifest
}

async function buildExe() {
  const output = path.join(distRoot, "unsloth-image-installer.exe")
  const configPath = path.join(buildRoot, "sea-config.json")
  const assets = {}
  for (const file of [...PAYLOAD_FILES, "manifest.json"]) {
    assets[`payload/${file}`] = path.join(stageRoot, file)
  }

  const config = {
    main: path.join(here, "windows-installer.cjs"),
    output,
    disableExperimentalSEAWarning: true,
    execArgv: ["--no-warnings"],
    execArgvExtension: "none",
    assets,
  }
  await fs.writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`)

  const result = spawnSync(process.execPath, ["--build-sea", configPath], {
    cwd: pluginRoot,
    stdio: "inherit",
  })
  if (result.status !== 0) {
    throw new Error(`node --build-sea failed with exit code ${result.status}`)
  }
  return output
}

function addTarEntry(pack, entry) {
  return new Promise((resolve, reject) => {
    const header = {
      name: entry.name,
      mode: entry.mode ?? 0o644,
      mtime: new Date(0),
    }
    if (entry.type) header.type = entry.type

    const done = (error) => (error ? reject(error) : resolve())
    if (entry.type === "directory") pack.entry(header, done)
    else pack.entry(header, entry.content, done)
  })
}

async function tarGzip(entries) {
  const pack = tar.pack()
  const gzip = zlib.createGzip()
  const chunks = []

  const finished = new Promise((resolve, reject) => {
    gzip.on("data", (chunk) => chunks.push(chunk))
    gzip.on("end", resolve)
    gzip.on("error", reject)
  })
  pack.pipe(gzip)

  for (const entry of entries) await addTarEntry(pack, entry)
  pack.finalize()
  await finished
  return Buffer.concat(chunks)
}

function controlFiles(version) {
  const control = [
    "Package: opencode-unsloth-image",
    `Version: ${version}`,
    "Section: utils",
    "Priority: optional",
    "Architecture: all",
    "Maintainer: OpenCode Unsloth Plugin <local@example.invalid>",
    "Description: Local Unsloth image generation tools for OpenCode",
    " Adds unslothimage.generate/models/status tools and the Desktop settings tab.",
    " Images are generated by Unsloth Studio/Desktop running on this machine.",
    "",
  ].join("\n")

  const postinst = [
    "#!/bin/sh",
    "set -e",
    "echo 'Unsloth Image plugin installed to /etc/opencode/plugins/unsloth-image.'",
    "if command -v opencode >/dev/null 2>&1; then",
    "  echo 'Restart OpenCode (or run /reload) to load the plugin.'",
    "fi",
    "echo 'Set UNSLOTH_API_KEY or use Desktop Settings -> Unsloth Image.'",
    "exit 0",
    "",
  ].join("\n")

  const postrm = [
    "#!/bin/sh",
    "set -e",
    "rmdir /etc/opencode/plugins/unsloth-image 2>/dev/null || true",
    "rmdir /etc/opencode/plugins 2>/dev/null || true",
    "rmdir /etc/opencode 2>/dev/null || true",
    "exit 0",
    "",
  ].join("\n")

  return [
    { name: "control", content: Buffer.from(control), mode: 0o644 },
    { name: "postinst", content: Buffer.from(postinst), mode: 0o755 },
    { name: "postrm", content: Buffer.from(postrm), mode: 0o755 },
  ]
}

async function dataFilesFromDisk() {
  const base = "etc/opencode/plugins/unsloth-image"
  const directories = [
    "etc",
    "etc/opencode",
    "etc/opencode/plugins",
    base,
    `${base}/src`,
    `${base}/src/gui`,
    `${base}/dist`,
  ]
  const entries = directories.map((name) => ({
    name: `${name}/`,
    type: "directory",
    mode: 0o755,
  }))
  for (const file of PAYLOAD_FILES) {
    entries.push({
      name: `${base}/${file}`,
      content: await fs.readFile(path.join(stageRoot, file)),
      mode: 0o644,
    })
  }
  return entries
}

function arHeader(name, size) {
  const header = Buffer.alloc(60, 0x20)
  header.write(name.padEnd(16, " "), 0, 16, "ascii")
  header.write(Math.floor(Date.now() / 1000).toString().padEnd(12, " "), 16, 12, "ascii")
  header.write("0".padEnd(6, " "), 28, 6, "ascii")
  header.write("0".padEnd(6, " "), 34, 6, "ascii")
  header.write("100644".padEnd(8, " "), 40, 8, "ascii")
  header.write(String(size).padEnd(10, " "), 48, 10, "ascii")
  header.write("`\n", 58, 2, "ascii")
  return header
}

function arMember(name, content) {
  const padding = content.length % 2 === 1 ? Buffer.from("\n") : Buffer.alloc(0)
  return Buffer.concat([arHeader(name, content.length), content, padding])
}

function buildAr(members) {
  const parts = [Buffer.from("!<arch>\n")]
  for (const member of members) parts.push(arMember(member.name, member.content))
  return Buffer.concat(parts)
}

function readAr(buffer) {
  if (buffer.subarray(0, 8).toString("ascii") !== "!<arch>\n") {
    throw new Error("Invalid .deb archive header")
  }
  const members = []
  let offset = 8
  while (offset + 60 <= buffer.length) {
    const header = buffer.subarray(offset, offset + 60).toString("ascii")
    const name = header.slice(0, 16).trim()
    const size = Number(header.slice(48, 58).trim())
    if (!Number.isFinite(size)) throw new Error("Invalid .deb member size")
    const content = buffer.subarray(offset + 60, offset + 60 + size)
    members.push({ name, content })
    offset += 60 + size + (size % 2)
  }
  return members
}

async function tarEntries(buffer) {
  const extract = tar.extract()
  const entries = new Map()
  const finished = new Promise((resolve, reject) => {
    extract.on("entry", (header, stream, next) => {
      const chunks = []
      stream.on("data", (chunk) => chunks.push(chunk))
      stream.on("end", () => {
        entries.set(header.name, Buffer.concat(chunks))
        next()
      })
      stream.resume()
    })
    extract.on("finish", resolve)
    extract.on("error", reject)
  })
  extract.end(buffer)
  await finished
  return entries
}

async function verifyDeb(buffer) {
  const members = readAr(buffer)
  const names = members.map((member) => member.name)
  for (const expected of ["debian-binary", "control.tar.gz", "data.tar.gz"]) {
    if (!names.includes(expected)) throw new Error(`Missing .deb member: ${expected}`)
  }
  const control = members.find((member) => member.name === "control.tar.gz")
  const data = members.find((member) => member.name === "data.tar.gz")
  const controlEntries = await tarEntries(zlib.gunzipSync(control.content))
  const dataEntries = await tarEntries(zlib.gunzipSync(data.content))
  for (const expected of ["control", "postinst", "postrm"]) {
    if (!controlEntries.has(expected)) throw new Error(`Missing control file: ${expected}`)
  }
  for (const file of PAYLOAD_FILES) {
    const name = `etc/opencode/plugins/unsloth-image/${file}`
    const actual = dataEntries.get(name)
    if (!actual) throw new Error(`Missing payload file in .deb: ${file}`)
    const expected = await fs.readFile(path.join(stageRoot, file))
    if (!actual.equals(expected)) throw new Error(`Payload mismatch in .deb: ${file}`)
  }
}

async function buildDeb(manifest) {
  const version = manifest.version
  const output = path.join(distRoot, `opencode-unsloth-image_${version}_all.deb`)
  const controlTar = await tarGzip(controlFiles(version))
  const dataTar = await tarGzip(await dataFilesFromDisk())
  const deb = buildAr([
    { name: "debian-binary", content: Buffer.from("2.0\n") },
    { name: "control.tar.gz", content: controlTar },
    { name: "data.tar.gz", content: dataTar },
  ])
  await verifyDeb(deb)
  await fs.writeFile(output, deb)
  return output
}

async function writeChecksums(exePath, debPath) {
  const lines = []
  for (const file of [exePath, debPath]) {
    lines.push(`${sha256(await fs.readFile(file))}  ${path.basename(file)}`)
  }
  await fs.writeFile(path.join(distRoot, "SHA256SUMS"), `${lines.join("\n")}\n`)
}

async function main() {
  await fs.mkdir(distRoot, { recursive: true })
  const manifest = await stagePayload()
  const exePath = await buildExe()
  const debPath = await buildDeb(manifest)
  await writeChecksums(exePath, debPath)

  const exeSize = (await fs.stat(exePath)).size
  const debSize = (await fs.stat(debPath)).size
  console.log("")
  console.log("Installer artifacts:")
  console.log(`  ${exePath} (${humanSize(exeSize)})`)
  console.log(`  ${debPath} (${humanSize(debSize)})`)
  console.log(`  ${path.join(distRoot, "SHA256SUMS")}`)
}

await main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
